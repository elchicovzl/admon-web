/**
 * Get municipios for a specific departamento
 */
export function getMunicipiosPorDepartamento(departamento: string): string[] {
  return MUNICIPIOS_POR_DEPARTAMENTO[departamento] || []
}

/**
 * Get departamento label from value
 */
export function getDepartamentoLabel(value: string): string {
  const dept = DEPARTAMENTOS_COLOMBIA.find((d) => d.value === value)
  return dept?.label || value
}
